def tier_of(score):
    if score >= 9.3: return "S"
    if score >= 8.8: return "A+"
    if score >= 8.2: return "A"
    if score >= 7.5: return "B+"
    if score >= 7.0: return "B"
    if score >= 6.5: return "C+"
    if score >= 6.0: return "C"
    if score >= 5.0: return "D"
    return "E"

